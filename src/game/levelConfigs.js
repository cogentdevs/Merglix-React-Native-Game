export function getLevelTimerSeconds(level) {
  const safeLevel = Math.max(1, Math.floor(Number(level) || 1));
  return 60 + Math.floor((safeLevel - 1) / 10) * 10;
}

function levelConfig({level, rows, columns, productTypes, copiesByType,
  difficulty, targetMatches}) {
  const totalItemCount = Object.values(copiesByType)
    .reduce((total, count) => total + count, 0);
  const durationSeconds = getLevelTimerSeconds(level);
  return {
    id: level,
    level,
    rows,
    columns,
    shelfCount: rows,
    productTypes,
    productTypeCount: productTypes.length,
    copiesByType,
    matchSize: 3,
    matchCount: targetMatches,
    targetMatches,
    totalItemCount,
    matchReward: MATCH_REWARD,
    completionReward: getLevelCompletionReward(level),
    durationSeconds,
    timerSeconds: durationSeconds,
    difficulty,
    shelf: `classic${rows}`,
    generatedShelves: false,
  };
}

